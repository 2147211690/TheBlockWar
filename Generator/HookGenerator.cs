using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace TheBlockWar.SourceGenerators;

[Generator]
public class HookGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // 1. 注入特性定义
        context.RegisterPostInitializationOutput(static ctx =>
        {
            ctx.AddSource("BuffHookAttribute.g.cs", """
// <auto-generated/>
using System;

namespace TheBlockWar.Scripts.Games.Buffs
{
    [AttributeUsage(AttributeTargets.Method, Inherited = false, AllowMultiple = false)]
    public sealed class BuffHookAttribute : Attribute { }
}
""");

            ctx.AddSource("RegionHookAttribute.g.cs", """
// <auto-generated/>
using System;

namespace TheBlockWar.Scripts.Games.Regions
{
    [AttributeUsage(AttributeTargets.Method, Inherited = false, AllowMultiple = false)]
    public sealed class RegionHookAttribute : Attribute { }
}
""");
        });

        // 2. 收集所有带 [BuffHook] 或 [RegionHook] 的方法
        var provider = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => node is MethodDeclarationSyntax { AttributeLists.Count: > 0 },
                transform: static (ctx, ct) => ExtractMethodInfo(ctx, ct))
            .Where(static m => m is not null)
            .Collect();

        // 3. 生成 Hook 类
        context.RegisterSourceOutput(provider, static (spc, methods) =>
        {
            if (methods.IsDefaultOrEmpty) return;

            var sb = new StringBuilder();
            foreach (var method in methods)
            {
                if (method is null) continue;
                sb.AppendLine(GenerateHookMethod(method));
            }

            var source = $$"""
// <auto-generated/>
#nullable enable
using System;
using System.Linq;
using TheBlockWar.Scripts.Tools;
using TheBlockWar.Scripts.Games.Buffs;
using TheBlockWar.Scripts.Games.Regions;


namespace TheBlockWar.Scripts.Games.Simulations
{
    public static partial class Hook
    {
{{sb.ToString()}}
    }
}
""";
            spc.AddSource("HookMethods.g.cs", source);
        });
    }

    private static HookMethod? ExtractMethodInfo(GeneratorSyntaxContext context, CancellationToken ct)
    {
        var syntax = (MethodDeclarationSyntax)context.Node;
        var symbol = context.SemanticModel.GetDeclaredSymbol(syntax, ct);
        if (symbol is null) return null;

        bool hasBuffHook = false;
        bool hasRegionHook = false;
        foreach (var attr in symbol.GetAttributes())
        {
            var attrName = attr.AttributeClass?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            if (attrName is "global::TheBlockWar.Scripts.Games.Buffs.BuffHookAttribute")
                hasBuffHook = true;
            else if (attrName is "global::TheBlockWar.Scripts.Games.Regions.RegionHookAttribute")
                hasRegionHook = true;
        }
        if (!hasBuffHook && !hasRegionHook) return null;

        if (!symbol.Name.StartsWith("On")) return null;

        var parameters = symbol.Parameters;
        if (parameters.Length == 0) return null;

        if (hasBuffHook)
            return ExtractBuffHook(symbol, parameters);

        return ExtractRegionHook(symbol, parameters);
    }

    private static HookMethod? ExtractBuffHook(IMethodSymbol symbol, ImmutableArray<IParameterSymbol> parameters)
    {
        IParameterSymbol? unitParam = null;
        foreach (var p in parameters)
        {
            var typeStr = p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            if (typeStr == "global::TheBlockWar.Scripts.Games.GameStates.IReadOnlyUnitState")
            {
                unitParam = p;
                break;
            }
        }
        if (unitParam is null) return null;

        IParameterSymbol? buffCountParam = null;
        foreach (var p in parameters)
        {
            if (p.Type.SpecialType == SpecialType.System_Int32 && p.Name == "buffCount")
            {
                buffCountParam = p;
                break;
            }
        }

        var hookParameters = new List<Parameter>();
        var callArguments = new List<CallArgument>();

        hookParameters.Add(new Parameter(
            unitParam.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
            "unit",
            unitParam.RefKind));

        foreach (var p in parameters)
        {
            if (p == buffCountParam)
            {
                callArguments.Add(new CallArgument("buffState.Count", RefKind.None));
                continue;
            }
            if (p == unitParam)
            {
                callArguments.Add(new CallArgument("unit", RefKind.None));
                continue;
            }

            string paramName = p.Name;
            string globalType = p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

            if (globalType == "global::TheBlockWar.Scripts.Games.Simulations.SimObject" && paramName == "obj")
                paramName = "simObj";

            hookParameters.Add(new Parameter(globalType, paramName, p.RefKind));
            callArguments.Add(new CallArgument(paramName, p.RefKind));
        }

        string hookMethodName = "Buff" + symbol.Name.Substring(2);
        string returnType = symbol.ReturnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        return new HookMethod(
            symbol.Name,
            hookMethodName,
            returnType,
            hookParameters,
            callArguments,
            HookKind.Buff);
    }

    private static HookMethod? ExtractRegionHook(IMethodSymbol symbol, ImmutableArray<IParameterSymbol> parameters)
    {
        // 查找 Vector2I regionCoords（接口定义中的名字）
        IParameterSymbol? regionCoordsParam = null;
        foreach (var p in parameters)
        {
            var typeStr = p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            if (typeStr == "global::Godot.Vector2I" && p.Name == "regionCoords")
            {
                regionCoordsParam = p;
                break;
            }
        }
        if (regionCoordsParam is null) return null;

        // 查找 SimObject obj
        IParameterSymbol? objParam = null;
        foreach (var p in parameters)
        {
            var typeStr = p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            if (typeStr == "global::TheBlockWar.Scripts.Games.Simulations.SimObject" && p.Name == "obj")
            {
                objParam = p;
                break;
            }
        }
        if (objParam is null) return null;

        var hookParameters = new List<Parameter>();
        var callArguments = new List<CallArgument>();

        // Hook 签名第一位：tileCoords（接口里叫 regionCoords）
        hookParameters.Add(new Parameter(
            regionCoordsParam.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
            "tileCoords",
            regionCoordsParam.RefKind));

        foreach (var p in parameters)
        {
            if (p == regionCoordsParam)
            {
                // 调用接口时，regionCoords 参数传入 tileCoords
                callArguments.Add(new CallArgument("tileCoords", RefKind.None));
                continue;
            }
            if (p == objParam)
            {
                hookParameters.Add(new Parameter(
                    p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                    "simObj",
                    p.RefKind));
                callArguments.Add(new CallArgument("simObj", RefKind.None));
                continue;
            }

            string paramName = p.Name;
            string globalType = p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            hookParameters.Add(new Parameter(globalType, paramName, p.RefKind));
            callArguments.Add(new CallArgument(paramName, p.RefKind));
        }

        string hookMethodName = "Region" + symbol.Name.Substring(2);
        string returnType = symbol.ReturnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        return new HookMethod(
            symbol.Name,
            hookMethodName,
            returnType,
            hookParameters,
            callArguments,
            HookKind.Region);
    }

    private static string GenerateHookMethod(HookMethod method)
    {
        var paramList = string.Join(", ", method.HookParameters.Select(p =>
        {
            var prefix = p.RefKind switch
            {
                RefKind.Ref => "ref ",
                RefKind.Out => "out ",
                RefKind.In => "in ",
                _ => ""
            };
            return $"{prefix}{p.GlobalTypeName} {p.Name}";
        }));

        var args = string.Join(", ", method.CallArguments.Select(a =>
        {
            var prefix = a.RefKind switch
            {
                RefKind.Ref => "ref ",
                RefKind.Out => "out ",
                RefKind.In => "in ",
                _ => ""
            };
            return prefix + a.Text;
        }));

        var hasSimObj = paramList.IndexOf("simObj", StringComparison.Ordinal) != -1;
        if (method.Kind == HookKind.Buff)
        {
            return hasSimObj
                ? $$"""
                            public static {{method.ReturnType}} {{method.HookMethodName}}({{paramList}})
                            {
                                simObj.PushContext(new SimContext(unit.Id));
                                foreach (var buffState in unit.BuffsStatic)
                                {
                                    buffState.BuffName.GetBuffInfo().Hook
                                        .{{method.InterfaceMethodName}}({{args}});
                                }
                                simObj.PopContext();
                            }
                    """
                : $$"""
                            public static {{method.ReturnType}} {{method.HookMethodName}}({{paramList}})
                            {
                                foreach (var buffState in unit.BuffsStatic)
                                {
                                    buffState.BuffName.GetBuffInfo().Hook
                                        .{{method.InterfaceMethodName}}({{args}});
                                }
                            }
                    """;
        }
        else
        {
            return 
                hasSimObj
                ? $$"""
                            public static {{method.ReturnType}} {{method.HookMethodName}}({{paramList}})
                            {
                                simObj.PushContext(new SimContext(0));
                                var tile = simObj.State.TileMapState.GetTile(tileCoords);
                                foreach (var regionState in tile.RegionsStatic)
                                {
                                    regionState.RegionName.GetRegionInfo().Hook
                                        .{{method.InterfaceMethodName}}({{args}});
                                }
                                simObj.PopContext();
                            }
                    """
                : $$"""
                               public static {{method.ReturnType}} {{method.HookMethodName}}({{paramList}})
                               {
                                   var tile = simObj.State.TileMapState.GetTile(tileCoords);
                                   foreach (var regionState in tile.RegionsStatic)
                                   {
                                       regionState.RegionName.GetRegionInfo().Hook
                                           .{{method.InterfaceMethodName}}({{args}});
                                   }
                               }
                    """;
        }
    }

    private enum HookKind { Buff, Region }

    private class HookMethod(
        string interfaceMethodName,
        string hookMethodName,
        string returnType,
        List<Parameter> hookParameters,
        List<CallArgument> callArguments,
        HookKind kind)
    {
        public string InterfaceMethodName { get; } = interfaceMethodName;
        public string HookMethodName { get; } = hookMethodName;
        public string ReturnType { get; } = returnType;
        public List<Parameter> HookParameters { get; } = hookParameters;
        public List<CallArgument> CallArguments { get; } = callArguments;
        public HookKind Kind { get; } = kind;
    }

    private class Parameter(
        string globalTypeName,
        string name,
        RefKind refKind)
    {
        public string GlobalTypeName { get; } = globalTypeName;
        public string Name { get; } = name;
        public RefKind RefKind { get; } = refKind;
    }

    private class CallArgument(
        string text,
        RefKind refKind)
    {
        public string Text { get; } = text;
        public RefKind RefKind { get; } = refKind;
    }
}