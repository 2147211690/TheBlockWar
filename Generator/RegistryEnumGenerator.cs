using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Generator;

[Generator]
public class RegistryEnumGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var registryFiles = context.AdditionalTextsProvider
            .Where(static file => file.Path.EndsWith(".tres", StringComparison.OrdinalIgnoreCase))
            .Select(static (file, ct) => file.GetText(ct)?.ToString())
            .Where(static text => text is not null)
            .Select(static (text, _) => ParseTres(text!))
            .Where(static info => info is not null)
            .Select(static (info, _) => info!.Value)
            .Collect();

        context.RegisterSourceOutput(registryFiles, static (spc, infos) =>
        {
            if (infos.IsDefaultOrEmpty) return;

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine();
            sb.AppendLine("namespace TheBlockWar.Scripts.Resources");
            sb.AppendLine("{");

            for (int i = 0; i < infos.Length; i++)
            {
                var info = infos[i];
                GenerateNamesClass(sb, info.ClassName, info.StringValues, i == infos.Length - 1);
            }

            sb.AppendLine("}");

            spc.AddSource("RegistryNames.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        });
    }

    private static void GenerateNamesClass(StringBuilder sb, string className, List<string> values, bool isLast)
    {
        sb.AppendLine($"    public static class {className}");
        sb.AppendLine("    {");
        for (int i = 0; i < values.Count; i++)
        {
            sb.AppendLine($"        public const string {values[i]} = \"{values[i]}\";");
        }
        sb.AppendLine("    }");
        if (!isLast)
            sb.AppendLine();
    }

    private static RegistryEnumInfo? ParseTres(string content)
    {
        if (!content.Contains("script_class=\"Registry\""))
            return null;

        var scanDirectories = ExtractScanDirectories(content);
        if (scanDirectories is null || scanDirectories.Count == 0)
            return null;

        var firstDir = scanDirectories[0];
        var folderName = ExtractLastFolderName(firstDir);
        if (folderName is null)
            return null;

        var className = folderName + "Names";

        var stringIds = ExtractStringIdsToUids(content);
        if (stringIds is null || stringIds.Count == 0)
            return null;

        var stringValues = stringIds.Keys.ToList();

        return new RegistryEnumInfo(className, stringValues);
    }

    private static string? ExtractLastFolderName(string directoryPath)
    {
        var trimmed = directoryPath.TrimEnd('/');
        var lastSlash = trimmed.LastIndexOf('/');
        if (lastSlash < 0) return null;
        var folder = trimmed.Substring(lastSlash + 1);
        if (folder.EndsWith("Infos"))
            folder = folder.Substring(0, folder.Length - 5);
        return folder;
    }

    private static List<string>? ExtractScanDirectories(string content)
    {
        var marker = "&\"scan_directories\": Array[String]([";
        var startIdx = content.IndexOf(marker, StringComparison.Ordinal);
        if (startIdx < 0) return null;

        startIdx += marker.Length;
        var endIdx = content.IndexOf("])", startIdx, StringComparison.Ordinal);
        if (endIdx < 0) return null;

        var arrayContent = content.Substring(startIdx, endIdx - startIdx);
        var directories = new List<string>();

        int pos = 0;
        while (pos < arrayContent.Length)
        {
            var quoteStart = arrayContent.IndexOf('"', pos);
            if (quoteStart < 0) break;
            var quoteEnd = arrayContent.IndexOf('"', quoteStart + 1);
            if (quoteEnd < 0) break;

            directories.Add(arrayContent.Substring(quoteStart + 1, quoteEnd - quoteStart - 1));
            pos = quoteEnd + 1;
        }

        return directories;
    }

    private static Dictionary<string, string>? ExtractStringIdsToUids(string content)
    {
        var marker = "_string_ids_to_uids = Dictionary[StringName, StringName]({";
        var startIdx = content.IndexOf(marker, StringComparison.Ordinal);
        if (startIdx < 0) return null;

        startIdx += marker.Length;
        var endIdx = content.IndexOf("})", startIdx, StringComparison.Ordinal);
        if (endIdx < 0) return null;

        var dictContent = content.Substring(startIdx, endIdx - startIdx);
        var result = new Dictionary<string, string>();

        int pos = 0;
        while (pos < dictContent.Length)
        {
            var keyStart = dictContent.IndexOf("&\"", pos, StringComparison.Ordinal);
            if (keyStart < 0) break;
            keyStart += 2;
            var keyEnd = dictContent.IndexOf('"', keyStart);
            if (keyEnd < 0) break;

            var key = dictContent.Substring(keyStart, keyEnd - keyStart);

            var valueStart = dictContent.IndexOf("&\"", keyEnd, StringComparison.Ordinal);
            if (valueStart < 0) break;
            valueStart += 2;
            var valueEnd = dictContent.IndexOf('"', valueStart);
            if (valueEnd < 0) break;

            var value = dictContent.Substring(valueStart, valueEnd - valueStart);
            result[key] = value;

            pos = valueEnd + 1;
        }

        return result;
    }

    private readonly struct RegistryEnumInfo(string className, List<string> stringValues)
    {
        public string ClassName { get; } = className;
        public List<string> StringValues { get; } = stringValues;
    }
}